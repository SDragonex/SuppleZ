function runEnrichment() {
  console.log('=== [SuppleZ Database Enricher] ===');

  let totalAdded = 0;

  Object.keys(NEW_ITEMS).forEach(catKey => {
    const filePath = path.join(DATA_DIR, `${catKey}.json`);
    if (!fs.existsSync(filePath)) {
      console.error(`Soubor ${catKey}.json nenalezen!`);
      return;
    }

    const currentItems = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const existingNames = new Set(currentItems.map(x => x.name.toLowerCase().trim()));
    const maxCurrentId = Math.max(...currentItems.map(x => x.id), 0);
    let nextId = maxCurrentId + 1;

    const toAdd = NEW_ITEMS[catKey].filter(newItem => !existingNames.has(newItem.name.toLowerCase().trim()));

    toAdd.forEach(item => {
      item.id = nextId++;
      currentItems.push(item);
      totalAdded++;
      console.log(`+ [${catKey}] ID ${item.id}: ${item.name}`);
    });

    fs.writeFileSync(filePath, JSON.stringify(currentItems, null, 2), 'utf8');
  });

  console.log(`\nCelkem přidáno ${totalAdded} nových biohackingových látek!`);
}

runEnrichment();
